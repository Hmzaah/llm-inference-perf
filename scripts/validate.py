"""Compare the estimates with the published numbers in validation/benchmarks.json.

Run:  python scripts/validate.py
Writes validation/results.md and prints the same tables.
"""

from __future__ import annotations

import json
from pathlib import Path

from llmperf import calc
from llmperf.specs import load_gpus, load_models

ROOT = Path(__file__).resolve().parent.parent
MODELS, GPUS = load_models(), load_gpus()


def pct_error(estimate: float, measured: float) -> str:
    return f"{(estimate - measured) / measured * 100:+.0f}%"


def tg128_estimate(model, gpu, precision, kv_precision, memory_eff, compute_eff=calc.DEFAULT_COMPUTE_EFF):
    """llama-bench tg128: 128 decode steps starting from an empty context."""
    total = sum(
        calc.decode_step(model, gpu, ctx, 1, precision, kv_precision,
                         compute_eff=compute_eff, memory_eff=memory_eff).time
        for ctx in range(128)
    )
    return 128 / total


def pp512_estimate(model, gpu, precision, compute_dtype):
    """llama-bench pp512: one prefill of a 512-token prompt."""
    return 512 / calc.prefill(model, gpu, 512, 1, precision, compute_dtype=compute_dtype).time


def llama_cpp_tables(b: dict) -> list[str]:
    model = MODELS[b["model"]]
    out = [
        "### Decode (tg128), llama.cpp, LLaMA 2 7B Q4_0, batch 1",
        "",
        f"Source: {b['source']} (flash attention on, the faster of the two runs). "
        f"Model file: {b['model_file']}.",
        "",
        "| GPU (as listed) | measured tok/s | estimate tok/s | error | implied bandwidth efficiency |",
        "|---|---|---|---|---|",
    ]
    for r in b["rows"]:
        gpu = GPUS[r["gpu"]]
        measured = r["fa_on"]["tg128"]
        est = tg128_estimate(model, gpu, b["precision"], b["kv_precision"], calc.DEFAULT_MEMORY_EFF)
        at_peak = tg128_estimate(model, gpu, b["precision"], b["kv_precision"], 1.0, compute_eff=1.0)
        out.append(f"| {r['chip_as_listed']} | {measured:.1f} | {est:.1f} | {pct_error(est, measured)} | "
                   f"{measured / at_peak:.0%} |")
    out += [
        "",
        "### Prefill (pp512), same runs",
        "",
        "llama.cpp can run quantized prompt processing with INT8 dot products (its own kernels) or by "
        "unpacking to FP16 for cuBLAS. Which path ran is not stated, so both estimates are shown.",
        "",
        "| GPU | measured tok/s | estimate, INT8 math | error | estimate, FP16 math | error |",
        "|---|---|---|---|---|---|",
    ]
    for r in b["rows"]:
        gpu = GPUS[r["gpu"]]
        measured = r["fa_on"]["pp512"]
        e8 = pp512_estimate(model, gpu, b["precision"], "int8")
        e16 = pp512_estimate(model, gpu, b["precision"], "fp16")
        out.append(f"| {gpu.name} | {measured:.0f} | {e8:.0f} | {pct_error(e8, measured)} | "
                   f"{e16:.0f} | {pct_error(e16, measured)} |")
    return out


def gaudi_table(b: dict) -> list[str]:
    model, gpu = MODELS[b["model"]], GPUS[b["gpu"]]
    out = [
        "### End-to-end throughput, Intel Gaudi 2, LLaMA 3.1 8B FP8, 1 card",
        "",
        f"Source: {b['source']} ({b['software']}). KV cache assumed FP8: {b['kv_precision_note']}",
        "",
        "| batch | input | output | measured tok/s | estimate tok/s | error | KV fits in 96 GB? |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in b["rows"]:
        t = calc.generation_time(model, gpu, r["input_len"], r["output_len"], r["batch"],
                                 b["precision"], b["kv_precision"])
        est = r["batch"] * r["output_len"] / t
        fits = calc.fits_in_memory(model, gpu, r["input_len"] + r["output_len"], r["batch"],
                                   b["precision"], b["kv_precision"])
        out.append(f"| {r['batch']} | {r['input_len']} | {r['output_len']} | {r['throughput_tps']} | "
                   f"{est:.0f} | {pct_error(est, r['throughput_tps'])} | {'yes' if fits else 'no'} |")
    return out


def main() -> None:
    bench = json.loads((ROOT / "validation" / "benchmarks.json").read_text(encoding="utf-8"))
    lines = [
        "# Validation results",
        "",
        "Generated by `python scripts/validate.py` with the default efficiency factors "
        f"(compute {calc.DEFAULT_COMPUTE_EFF}, memory {calc.DEFAULT_MEMORY_EFF}). "
        "Error = (estimate - measured) / measured. Positive means the tool is too optimistic.",
        "",
    ]
    lines += llama_cpp_tables(bench["llama_cpp"]) + [""] + gaudi_table(bench["gaudi"]) + [""]
    text = "\n".join(lines)
    (ROOT / "validation" / "results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
